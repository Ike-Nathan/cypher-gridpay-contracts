/**
 * Extract a numeric Soroban contract error code from any error representation.
 */
export function extractErrorCode(raw: unknown): number | null {
  if (typeof raw === 'number' && Number.isInteger(raw) && raw >= 0) {
    return raw;
  }

  if (typeof raw === 'string') {
    // Matches: Error(Contract, #123) or Error(Contract, 123)
    const contractMatch = raw.match(/Error\(Contract,\s*#?(\d+)\)/i);
    if (contractMatch && contractMatch[1]) {
      return parseInt(contractMatch[1], 10);
    }

    // Matches: "code": 123 or code: 123
    const codeMatch = raw.match(/\bcode["']?\s*:\s*(\d+)/i);
    if (codeMatch && codeMatch[1]) {
      return parseInt(codeMatch[1], 10);
    }

    // Matches: error code 123 or contract error: 123
    const errMatch = raw.match(/(?:contract\s+error|error\s+code)\s*[:#]?\s*(\d+)/i);
    if (errMatch && errMatch[1]) {
      return parseInt(errMatch[1], 10);
    }

    // Pure number string
    if (/^\d+$/.test(raw.trim())) {
      return parseInt(raw.trim(), 10);
    }
  }

  if (raw && typeof raw === 'object') {
    const obj = raw as Record<string, unknown>;

    // Direct code field
    if (typeof obj['code'] === 'number' && Number.isInteger(obj['code'])) {
      return obj['code'];
    }

    // RPC simulateTransaction / error field
    if (typeof obj['error'] === 'string') {
      const code = extractErrorCode(obj['error']);
      if (code !== null) return code;
    }

    // JS Error object with message
    if (typeof obj['message'] === 'string') {
      const code = extractErrorCode(obj['message']);
      if (code !== null) return code;
    }

    // Nested result object
    if (obj['result'] && typeof obj['result'] === 'object') {
      const code = extractErrorCode(obj['result']);
      if (code !== null) return code;
    }
  }

  return null;
}

/**
 * Decode any raw error from Soroban RPC simulation or transaction submission
 * into a strongly-typed GridPayContractError.
 *
 * @param rawError Any error object, RPC response, string, or code
 * @param targetContract Optional contract hint ('payment' | 'escrow' | 'refund' | 'admin')
 * @returns Decoded GridPayContractError or null if not a recognized contract error
 */
export function decodeGridPayError(
  rawError: unknown,
  targetContract?: GridPayContractType
): GridPayContractError | null {
  const code = extractErrorCode(rawError);
  if (code === null) {
    return null;
  }

  // If contract hint provided, look up in that specific contract first
  if (targetContract) {
    const descriptor = ALL_CONTRACT_ERRORS.get(targetContract)?.get(code);
    if (descriptor) {
      return {
        ...descriptor,
        rawError,
      };
    }
  }

  // Look through contracts in standard priority order: payment -> escrow -> refund -> admin
  const searchOrder: GridPayContractType[] = ['payment', 'escrow', 'refund', 'admin'];
  for (const c of searchOrder) {
    const descriptor = ALL_CONTRACT_ERRORS.get(c)?.get(code);
    if (descriptor) {
      return {
        ...descriptor,
        rawError,
      };
    }
  }

  // Generic fallback if numeric code is recognized as contract error pattern
  return {
    contract: targetContract ?? 'unknown',
    code,
    name: `UnknownContractError_${code}`,
    enumName: 'Unknown',
    category: 'Unmapped',
    message: `Soroban contract reverted with unmapped error code ${code}.`,
    resolution: 'Consult contract source code or docs/ERROR_CODES.md for error resolution.',
    retryable: false,
    rawError,
  };
}

/**
 * Determine if an unknown error represents a recognized Soroban contract revert.
 */
export function isContractError(error: unknown): boolean {
  return extractErrorCode(error) !== null;
}

/**
 * Check if a contract error is transient/retryable (rate limits, timeouts, stale feeds).
 */
export function isRetryableError(error: unknown, targetContract?: GridPayContractType): boolean {
  const decoded = decodeGridPayError(error, targetContract);
  return decoded !== null && decoded.retryable;
}

/**
 * Returns a human-friendly error string with remediation guidance.
 */
export function formatDiagnosticError(error: unknown, targetContract?: GridPayContractType): string {
  const decoded = decodeGridPayError(error, targetContract);
  if (!decoded) {
    return error instanceof Error ? error.message : String(error);
  }
  return `[${decoded.contract.toUpperCase()}::${decoded.name} (#${decoded.code})] ${decoded.message}\nRemediation: ${decoded.resolution}`;
}
